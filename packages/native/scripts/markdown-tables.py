#!/usr/bin/env python3
"""Writes src/markdown-tables.zig: the Unicode and HTML tables the Markdown engine needs.

CommonMark 0.31.2 reads Unicode punctuation (general categories P and S) and Unicode whitespace
(Zs) for emphasis flanking, full case folding for link labels, and the HTML5 named character
references for entities. Run with the Python whose Unicode version the file should carry:

    python3 packages/native/scripts/markdown-tables.py > packages/native/src/markdown-tables.zig
    zig fmt packages/native/src/markdown-tables.zig
"""

import html.entities
import unicodedata

COLUMNS = 100


def ranges(predicate):
    result, start = [], None
    for cp in range(0x110000):
        if predicate(cp):
            if start is None:
                start = cp
        elif start is not None:
            result.append((start, cp - 1))
            start = None
    return result


def wrap(items, indent="    "):
    lines, line = [], indent
    for item in items:
        if len(line) + len(item) + 1 > COLUMNS:
            lines.append(line.rstrip())
            line = indent
        line += item + " "
    if line.strip():
        lines.append(line.rstrip())
    return "\n".join(lines)


def main():
    out = []
    out.append("//! Generated by scripts/markdown-tables.py from Unicode %s and the HTML5 entity list;" % unicodedata.unidata_version)
    out.append("//! do not edit. Read by markdown.zig.")
    out.append("")
    punctuation = ranges(lambda cp: unicodedata.category(chr(cp))[0] in "PS")
    out.append("/// Unicode punctuation (general categories P and S) as inclusive [first, last] pairs, sorted.")
    out.append("pub const punctuation_ranges = [_][2]u21{")
    out.append(wrap([".{ 0x%X, 0x%X }," % r for r in punctuation]))
    out.append("};")
    out.append("")
    spaces = [cp for cp in range(0x110000) if unicodedata.category(chr(cp)) == "Zs"]
    out.append("/// Unicode Zs code points; with tab, line feed, form feed and carriage return they are")
    out.append("/// CommonMark's Unicode whitespace.")
    out.append("pub const space_separators = [_]u21{")
    out.append(wrap(["0x%X," % cp for cp in spaces]))
    out.append("};")
    out.append("")
    # Single code point folds as runs [first, last, stride, delta]; longer folds listed apart.
    single, multi = [], []
    for cp in range(0x110000):
        folded = chr(cp).casefold()
        if folded == chr(cp):
            continue
        if len(folded) == 1:
            single.append((cp, ord(folded) - cp))
        else:
            multi.append((cp, [ord(c) for c in folded]))
    runs = []
    for cp, delta in single:
        if runs:
            first, last, stride, run_delta = runs[-1]
            if run_delta == delta and (cp - last == stride or (first == last and cp - last in (1, 2))):
                runs[-1] = (first, cp, cp - last, delta)
                continue
        runs.append((cp, cp, 1, delta))
    out.append("/// Case folds to one code point: runs of { first, last, stride, delta }, sorted.")
    out.append("pub const fold_runs = [_]FoldRun{")
    out.append(wrap([".{ 0x%X, 0x%X, %d, %d }," % r for r in runs]))
    out.append("};")
    out.append("pub const FoldRun = struct { u21, u21, u8, i32 };")
    out.append("")
    out.append("/// Case folds to two or three code points, sorted by the folded code point.")
    out.append("pub const fold_multi = [_]FoldMulti{")
    out.append(wrap([".{ 0x%X, .{ %s } }," % (cp, ", ".join("0x%X" % c for c in (f + [0])[:3])) for cp, f in multi]))
    out.append("};")
    out.append("pub const FoldMulti = struct { u21, [3]u21 };")
    out.append("")
    names = sorted(name[:-1] for name in html.entities.html5 if name.endswith(";"))
    out.append("/// HTML5 named character references (without the semicolon), sorted, NUL-terminated each.")
    out.append("pub const entity_names =")
    blob, line = [], ""
    for name in names:
        piece = name + "\\x00"
        if len(line) + len(piece) > COLUMNS - 12:
            blob.append(line)
            line = ""
        line += piece
    blob.append(line)
    out.append(" ++\n".join('    "%s"' % b for b in blob) + ";")
    out.append("")
    out.append("/// The code points of entity_names[i]: one or two, the second 0 when absent.")
    out.append("pub const entity_code_points = [_][2]u21{")
    pairs = []
    for name in names:
        value = [ord(c) for c in html.entities.html5[name + ";"]]
        pairs.append(".{ 0x%X, 0x%X }," % (value[0], value[1] if len(value) > 1 else 0))
    out.append(wrap(pairs))
    out.append("};")
    print("\n".join(out))


main()
