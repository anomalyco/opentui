const s = state ?? { query: "" }
let query = s.query
if (event.type === "key") {
  if (event.key === "escape") query = ""
  else if (event.key === "backspace") query = query.slice(0, -1)
  else query += event.key
}

// Subsequence match: consecutive and word-start hits score more, shorter names win ties.
function score(name, q) {
  const n = name.toLowerCase()
  let i = 0
  let total = 0
  let last = -2
  for (let j = 0; j < n.length && i < q.length; j++) {
    if (n[j] !== q[i]) continue
    total += j === last + 1 ? 3 : 1
    if (j === 0 || n[j - 1] === " ") total += 2
    last = j
    i++
  }
  return i === q.length ? total + 1 - n.length / 100 : -1
}

const q = query.toLowerCase()
const top = COMMANDS.map((name) => ({ name, score: score(name, q) }))
  .filter((m) => m.score >= 0)
  .sort((a, b) => b.score - a.score || (a.name < b.name ? -1 : 1))
  .slice(0, 10)

const slots = { panel: { title: "> " + query, lines: top.map((m) => m.name) }, status: top.length + " commands" }
if (event.type === "init") return { state: { query }, slots, commands: [{ name: "palette.open", title: "Open Palette", key: "ctrl+p" }] }
return { state: { query }, slots }
