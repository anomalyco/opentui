// Generates crates/opentui/tests/post_reference.txt: the cells OpenTUI Core's post-processing produces on a fixed
// pattern, which crates/opentui/tests/post.rs compares the Rust port against.
//
// Math.random is replaced by the SplitMix64 generator the Rust port seeds its effects with, so noise, clouds, and
// distortion draw the same numbers in both.
//
// Usage: OPENTUI_ROOT=/path/to/opentui bun scripts/post-reference.ts

import { writeFileSync } from "node:fs"
import { resolve } from "node:path"

const root = process.env.OPENTUI_ROOT
if (root === undefined || root.trim() === "") {
  throw new Error("set OPENTUI_ROOT to an OpenTUI checkout")
}
const core = resolve(root, "packages/core/src")
const { OptimizedBuffer, ResourceContext } = await import(`${core}/buffer.ts`)
const { RGBA } = await import(`${core}/lib/RGBA.ts`)
const Matrices = await import(`${core}/post/matrices.ts`)
const Filters = await import(`${core}/post/filters.ts`)
const Effects = await import(`${core}/post/effects.ts`)

// Keep in sync with `pattern` in crates/opentui/tests/post.rs.
const WIDTH = 12
const HEIGHT = 6
const SEED = 42n

function pattern(x: number, y: number): { fg: number[]; bg: number[]; char: string } {
  const fg =
    (x + 2 * y) % 5 === 0
      ? [255, 255, 255]
      : [(x * 37 + y * 11) % 256, (x * 53 + y * 29 + 100) % 256, (x * 17 + y * 71 + 200) % 256]
  const bg = [(x * 23 + y * 41 + 50) % 256, (x * 7 + y * 61) % 256, (x * 89 + y * 13 + 30) % 256]
  return { fg, bg, char: String.fromCharCode(97 + ((x * 3 + y) % 26)) }
}

const MASK = (1n << 64n) - 1n
function seed(value: bigint): void {
  let state = value
  Math.random = () => {
    state = (state + 0x9e3779b97f4a7c15n) & MASK
    let z = state
    z = ((z ^ (z >> 30n)) * 0xbf58476d1ce4e5b9n) & MASK
    z = ((z ^ (z >> 27n)) * 0x94d049bb133111ebn) & MASK
    z = z ^ (z >> 31n)
    return Number(z >> 11n) / 2 ** 53
  }
}

const owner = new ResourceContext({
  objectCapacity: 65536,
  renderCellsMax: 1000000,
})
let count = 0
const lines = [
  "# Generated by scripts/post-reference.ts from OpenTUI Core's post-processing under Bun. Do not edit.",
  `# A ${WIDTH}x${HEIGHT} pattern; per case, each cell's foreground and background as rrggbbaa and its character.`,
]

function run(name: string, apply: (buffer: any) => void): void {
  const buffer = OptimizedBuffer.create(WIDTH, HEIGHT, "unicode", {
    owner,
    id: `reference-${count++}`,
  })
  for (let y = 0; y < HEIGHT; y++) {
    for (let x = 0; x < WIDTH; x++) {
      const cell = pattern(x, y)
      buffer.drawText(cell.char, x, y, RGBA.fromInts(...cell.fg, 255), RGBA.fromInts(...cell.bg, 255))
    }
  }
  apply(buffer)
  buffer.withBuffers(({ fg, bg, char }: { fg: Uint16Array; bg: Uint16Array; char: Uint32Array }) => {
    const hex = (plane: Uint16Array) =>
      Array.from(plane, (value) => (value & 0xff).toString(16).padStart(2, "0")).join("")
    const chars = Array.from(char, (value) => value.toString(16).padStart(2, "0")).join("")
    lines.push(`case ${name}`, `fg ${hex(fg)}`, `bg ${hex(bg)}`, `chars ${chars}`)
  })
  buffer.destroy()
}

const matrices: [string, Float32Array][] = [
  ["sepia", Matrices.SEPIA_MATRIX],
  ["protanopia_simulation", Matrices.PROTANOPIA_SIM_MATRIX],
  ["deuteranopia_simulation", Matrices.DEUTERANOPIA_SIM_MATRIX],
  ["tritanopia_simulation", Matrices.TRITANOPIA_SIM_MATRIX],
  ["achromatopsia", Matrices.ACHROMATOPSIA_MATRIX],
  ["protanopia_compensation", Matrices.PROTANOPIA_COMP_MATRIX],
  ["deuteranopia_compensation", Matrices.DEUTERANOPIA_COMP_MATRIX],
  ["tritanopia_compensation", Matrices.TRITANOPIA_COMP_MATRIX],
  ["technicolor", Matrices.TECHNICOLOR_MATRIX],
  ["solarization", Matrices.SOLARIZATION_MATRIX],
  ["synthwave", Matrices.SYNTHWAVE_MATRIX],
  ["greenscale", Matrices.GREENSCALE_MATRIX],
  ["grayscale", Matrices.GRAYSCALE_MATRIX],
  ["invert", Matrices.INVERT_MATRIX],
]
run("original", () => {})
for (const [name, matrix] of matrices) {
  run(name, (buffer) => buffer.colorMatrixUniform(matrix, 1.0, 3))
}
run("sepia_half", (buffer) => buffer.colorMatrixUniform(Matrices.SEPIA_MATRIX, 0.5, 3))
run("grayscale_foreground", (buffer) => buffer.colorMatrixUniform(Matrices.GRAYSCALE_MATRIX, 1.0, 1))
run("scanlines", (buffer) => Filters.applyScanlines(buffer, 0.8, 2))
run("invert_filter", (buffer) => Filters.applyInvert(buffer, 0.75))
run("brightness", (buffer) => Filters.applyBrightness(buffer, 0.2))
run("gain", (buffer) => Filters.applyGain(buffer, 0.6))
run("saturation", (buffer) => Filters.applySaturation(buffer, undefined, 1.8))
run("noise", (buffer) => {
  seed(SEED)
  Filters.applyNoise(buffer, 0.3)
})
run("chromatic_aberration", (buffer) => Filters.applyChromaticAberration(buffer, 2))
run("ascii_art", (buffer) => Filters.applyAsciiArt(buffer))
run("bloom", (buffer) => new Filters.BloomEffect(0.6, 0.3, 2).apply(buffer))
run("vignette", (buffer) => new Effects.VignetteEffect(0.7).apply(buffer))
run("clouds", (buffer) => {
  seed(SEED)
  new Effects.CloudsEffect(0.2, 0.001, 0.8, 0.9).apply(buffer, 500)
})
run("rainbow", (buffer) => new Effects.RainbowTextEffect(0.01, 1.0, 1.0, 3.0).apply(buffer, 250))
run("crt", (buffer) => new Effects.CRTRollingBarEffect(4, 0.3, 0.5, 0.3).apply(buffer, 500))
run("distortion", (buffer) => {
  seed(SEED)
  // Core's renderer passes milliseconds, but the effect's parameters are per second; pass seconds, as Rust does.
  new Effects.DistortionEffect({ colorGlitchChance: 0.4, maxGlitchLines: 4 }).apply(buffer, 2)
})
owner.destroy()

const output = resolve(import.meta.dir, "../crates/opentui/tests/post_reference.txt")
writeFileSync(output, `${lines.join("\n")}\n`)
console.log(`wrote ${output}`)
