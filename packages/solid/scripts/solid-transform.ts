import { transformAsync, types, type NodePath, type PluginObj } from "@babel/core"
// @ts-expect-error - Types not important.
import ts from "@babel/preset-typescript"
// @ts-expect-error - Types not important.
import solid from "babel-preset-solid"

export type ResolveImportPath = (specifier: string) => string | null

export interface TransformSolidSourceOptions {
  filename: string
  moduleName?: string
  resolvePath?: ResolveImportPath
}

const nodeModulesPattern = /[/\\]node_modules[/\\]/
const tsPattern = /\.[cm]?tsx?$/
const jsxPattern = /\.[cm]?[jt]sx$/
// These are the literal module-call forms the previous resolver rewrote for the
// Solid build and runtime-plugin transform. They are a compatibility surface,
// not an inference about what current OpenTUI internals happen to call.
const moduleCallPatterns = [
  "require.resolve",
  "System.import",
  "jest.genMockFromModule",
  "jest.mock",
  "jest.unmock",
  "jest.doMock",
  "jest.dontMock",
  "jest.setMock",
  "jest.requireActual",
  "jest.requireMock",
  "require.requireActual",
  "require.requireMock",
]

export function stripQueryAndHash(path: string): string {
  const searchIndex = path.indexOf("?")
  const hashIndex = path.indexOf("#")
  const end = [searchIndex, hashIndex].filter((index) => index >= 0).sort((a, b) => a - b)[0]
  return end === undefined ? path : path.slice(0, end)
}

export function isNodeModulesPath(path: string): boolean {
  return nodeModulesPattern.test(path)
}

export function resolveNodeSolidRuntimeImport(specifier: string): string | null {
  switch (specifier) {
    case "solid-js":
      return "solid-js/dist/solid.js"
    case "solid-js/store":
      return "solid-js/store/dist/store.js"
    default:
      return null
  }
}

function createImportResolver(options: TransformSolidSourceOptions): PluginObj {
  const visited = new WeakSet<NodePath>()
  const rewriteLiteral = (source: NodePath<types.Node | null | undefined> | undefined) => {
    if (!source?.isStringLiteral()) return
    const replacement = options.resolvePath?.(source.node.value) ?? source.node.value
    if (replacement) source.replaceWith(types.stringLiteral(replacement))
  }
  const rewriteSource = (
    path: NodePath<types.ImportDeclaration | types.ExportNamedDeclaration | types.ExportAllDeclaration>,
  ) => {
    if (visited.has(path)) return
    visited.add(path)
    rewriteLiteral(path.get("source"))
  }
  const rewriteImports = (path: NodePath<types.Program>) => {
    path.traverse({
      ImportDeclaration: rewriteSource,
      ExportNamedDeclaration: rewriteSource,
      ExportAllDeclaration: rewriteSource,
      CallExpression(path) {
        if (visited.has(path)) return
        const callee = path.get("callee")
        const matches =
          callee.isImport() ||
          callee.isIdentifier({ name: "require" }) ||
          (callee.isMemberExpression() && moduleCallPatterns.some((pattern) => callee.matchesPattern(pattern)))
        if (!matches) return
        visited.add(path)
        rewriteLiteral(path.get("arguments")[0])
      },
    })
  }
  return {
    name: "opentui-import-resolver",
    visitor: {
      // The exit pass also handles runtime imports generated by the Solid preset.
      Program: { enter: rewriteImports, exit: rewriteImports },
    },
  }
}

export async function transformSolidSource(code: string, options: TransformSolidSourceOptions): Promise<string> {
  const filename = stripQueryAndHash(options.filename)
  const plugins = options.resolvePath ? [createImportResolver(options)] : []

  const presets = []

  if (jsxPattern.test(filename)) {
    presets.push([
      solid,
      {
        moduleName: options.moduleName ?? "@opentui/solid",
        generate: "universal",
      },
    ])
  }

  if (tsPattern.test(filename)) {
    presets.push([ts])
  }

  const transformed = await transformAsync(code, {
    filename,
    configFile: false,
    babelrc: false,
    plugins,
    presets,
  })

  return transformed?.code ?? code
}
